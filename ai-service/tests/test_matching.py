"""Отбор кандидатов по буквам: что именно сервис показывает модели.

Опорные случаи здесь — не выдуманные, а те, на которых подбор ломался в поле: фамилия
в дательном падеже, магазин, названный улицей, магазин, названный номером, и «ё».
Это же множество должно проверяться на стороне lsFusion (там свои правила похожести),
поэтому случаи названы одинаково: расхождение двух реализаций видно по имени теста, а
не по чтению обеих.
"""

from app.matching import normalize, prune, similarity, tokens


def score(query: str, candidate: str) -> float:
    return similarity(tokens(query), candidate)


class TestНормализация:
    def test_ё_и_регистр_не_различаются(self):
        # «Артём» в справочнике и «артема» в запросе — один человек
        assert normalize("Артём") == "артем"
        assert normalize("САНТА") == "санта"

    def test_служебные_и_короткие_слова_выброшены(self):
        # «в магазине на» есть в каждой второй фразе и в половине названий: совпадение
        # по ним не значит ничего
        assert tokens("в магазине на Ленина") == ["ленина"]
        # keep_stop_words нужен там, где важен сам текст, а не поиск
        assert "на" in tokens("в магазине на Ленина", keep_stop_words=True)

    def test_двузначный_номер_не_попадает_в_поиск(self):
        # «18» короче трёх символов и отбрасывается вместе с предлогами. Номер магазина
        # ищет сервер (hasNumber по отдельному числу), и это его ответственность —
        # сервис не должен делать вид, что тоже умеет
        assert tokens("С - 18 в 204") == ["204"]


class TestПохожесть:
    def test_фамилия_в_дательном_падеже_находит_запись(self):
        # «Иванову» → «Иванов Сергей Петрович»: русский хвост отваливается общим началом
        assert score("Поставь Иванову проверить витрину", "Иванов Сергей Петрович") == 0.85

    def test_однофамилец_не_подтягивается(self):
        # «Иваненко» на «Иванову» не похож ни началом, ни целиком — 0, а не «немного»
        assert score("Поставь Иванову проверить витрину", "Иваненко Пётр") == 0.0

    def test_магазин_назван_улицей(self):
        # в запросе «магазин на Ленина», в справочнике «Санта на Ленина» — целиком не
        # совпадает никогда, различающее слово одно
        assert score("в магазине на Ленина", "Санта на Ленина") == 1.0
        assert score("в магазине на Ленина", "Санта Уручье") == 0.0

    def test_магазин_назван_номером(self):
        assert score("наведи порядок в 204", "С - 204 г. Минск") == 1.0

    def test_ё_не_мешает(self):
        # чистый случай «ё»: слова одной длины, различие только в букве. Сервер выравнивает
        # её так же (AiTools.deyo) — это единственное правило, общее у двух половин
        assert score("проверить Берёзку", "Березка на Мира") > 0
        assert score("проверить Березку", "Берёзка на Мира") > 0

    def test_короткое_склонение_сервис_прощает_а_сервер_нет(self):
        # «Артёма» → «Артем»: здесь работает не «ё», а префиксное правило — оно
        # срабатывает с пяти символов. У сервера «огрызок» не трогает слова короче семи,
        # и эта же пара у него НЕ совпадает (ai_draft_check, секция O). Расхождение
        # известное и названо с обеих сторон; выравнивать пороги — отдельная работа.
        assert score("позвать Артёма", "Артем Кузнецов") == 0.85

    def test_запрос_без_значащих_слов_никого_не_выбирает(self):
        # «срочно» — стоп-слово; пустой список слов не должен давать ложных совпадений
        assert score("срочно", "Санта на Ленина") == 0.0

    def test_второе_совпавшее_слово_поднимает_кандидата(self):
        # оба слова «Иванову Сергею» нашлись у полного тёзки — он должен обойти
        # однофамильца, у которого совпала только фамилия
        assert score("Иванову Сергею", "Иванов Сергей") == 0.9775
        assert score("Иванову Сергею", "Иванов Пётр") == 0.85

    def test_надбавка_не_видна_поверх_точного_совпадения(self):
        # оценка упирается в потолок 1.0, поэтому «Санта на Ленина 15а» и «Санта на
        # Ленина» на запрос «Ленина 15а» неразличимы. Это ограничение, а не опечатка:
        # различать их — работа сервера, у него есть номер объекта отдельным полем
        assert score("Ленина 15а", "Санта на Ленина 15а") == 1.0
        assert score("Ленина 15а", "Санта на Ленина") == 1.0


class TestОбрезкаСписка:
    ITEMS = [
        {"id": "a", "name": "Санта на Ленина"},
        {"id": "b", "name": "Санта Уручье"},
        {"id": "c", "name": "Санта на Ленина 15"},
    ]

    def test_остаются_самые_похожие(self):
        kept = prune(self.ITEMS, lambda x: x["name"], "на Ленина 15", 2)
        assert [x["id"] for x in kept] == ["a", "c"]

    def test_при_равных_оценках_сохраняется_порядок_сервера(self):
        # сервер отбирал по делу (рядом, названо, есть роль) — его порядок нельзя терять
        kept = prune(self.ITEMS, lambda x: x["name"], "", 3)
        assert [x["id"] for x in kept] == ["a", "b", "c"]

    def test_keep_переживает_любые_буквы(self):
        # объект, на котором человек стоит, обязан оказаться перед моделью: «поставь
        # проверку здесь» не содержит ни одного слова из его названия
        kept = prune(self.ITEMS, lambda x: x["name"], "ззз", 1, keep=lambda x: x["id"] == "b")
        assert [x["id"] for x in kept] == ["b"]

    def test_лимит_соблюдается(self):
        assert len(prune(self.ITEMS, lambda x: x["name"], "Санта", 2)) == 2
